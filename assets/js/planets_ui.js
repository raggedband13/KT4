const tabs = [...document.querySelectorAll(".planet_tab")];
const previous = document.querySelector("#planet_prev");
const next = document.querySelector("#planet_next");
const title = document.querySelector("#planet_name");
const description = document.querySelector("#planet_description");
const factsTitle = document.querySelector("#facts_title");
const facts = document.querySelector("#planet_facts");
const articleTitle = document.querySelector("#article_title");
const articleText = document.querySelector("#article_text");
const articleNote = document.querySelector("#article_note");
let currentIndex = 0;

function scrollActiveTab() {
  tabs[currentIndex].scrollIntoView({ behavior: "smooth", block: "nearest", inline: "center" });
}

function attachFactButtons() {
  document.querySelectorAll("[data-fact-toggle]").forEach((button) => {
    button.addEventListener("click", () => {
      const detail = button.parentElement.querySelector(".fact_detail");
      const isOpen = detail.classList.toggle("is_open");
      button.textContent = isOpen ? "Скрыть" : "Подробнее";
    });
  });
}

function showPlanet(index) {
  currentIndex = (index + window.planetData.length) % window.planetData.length;
  const data = window.planetData[currentIndex];
  title.textContent = data.title;
  description.textContent = data.description;
  factsTitle.textContent = `${data.title} в цифрах`;
  articleTitle.textContent = data.articleTitle;
  articleText.textContent = data.articleText;
  articleNote.textContent = data.articleNote;
  facts.innerHTML = data.facts
    .map(
      ([label, value, detail]) => `
    <div class="fact_card">
      <span>${label}</span>
      <strong>${value}</strong>
      <p class="fact_detail">${detail}</p>
      <button class="button" type="button" data-fact-toggle>Подробнее</button>
    </div>`,
    )
    .join("");
  attachFactButtons();
  tabs.forEach((tab, tabIndex) => tab.classList.toggle("active", tabIndex === currentIndex));
  scrollActiveTab();
  window.currentPlanetIndex = currentIndex;
  window.dispatchEvent(new CustomEvent("planetchange", { detail: { index: currentIndex } }));
}

tabs.forEach((tab, index) => tab.addEventListener("click", () => showPlanet(index)));
previous.addEventListener("click", () => showPlanet(currentIndex - 1));
next.addEventListener("click", () => showPlanet(currentIndex + 1));
showPlanet(0);
